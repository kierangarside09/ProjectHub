CREATE TABLE account (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(255) NOT NULL UNIQUE,
    hashed_password VARCHAR(255),
    created_at      TIMESTAMP WITH TIME ZONE
);

CREATE TABLE profile (
    account_id   BIGINT PRIMARY KEY REFERENCES account (id),
    display_name VARCHAR(30),
    location     VARCHAR(255),
    bio          VARCHAR(1000),
    skills       VARCHAR(200),
    gender       VARCHAR(20) CHECK (gender IN ('MALE', 'FEMALE', 'OTHER', 'PREFER_NOT_TO_SAY')),
    looking_for  VARCHAR(30) CHECK (looking_for IN (
        'DEVELOPER', 'DESIGNER', 'FRONTEND_DEVELOPER', 'BACKEND_DEVELOPER',
        'FULL_STACK_DEVELOPER', 'MOBILE_DEVELOPER', 'GAME_DEVELOPER',
        'DEVOPS_ENGINEER', 'DATA_SCIENTIST', 'QA_TESTER', 'PROJECT_MANAGER',
        'WRITER', 'ARTIST', 'MUSICIAN', 'MARKETING', 'MENTOR', 'CO_FOUNDER',
        'ANYTHING', 'NOT_LOOKING'))
);

CREATE TABLE project (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR(255),
    small_description VARCHAR(255)
);
